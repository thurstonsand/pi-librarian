#!/usr/bin/env node
// Regenerates extensions/librarian/github-languages.ts from GitHub Linguist, whose names and
// aliases are what GitHub search's language: qualifier accepts. Run: node scripts/generate-github-languages.mjs
import { writeFile } from "node:fs/promises";

const SOURCE =
  "https://raw.githubusercontent.com/github-linguist/linguist/main/lib/linguist/languages.yml";
const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Fetching ${SOURCE} failed with ${response.status}`);
}

const names = new Set();
let inAliases = false;
for (const line of (await response.text()).split("\n")) {
  const language = /^([^\s#][^:]*):\s*$/.exec(line);
  if (language) {
    names.add(language[1].replace(/^"|"$/g, ""));
    inAliases = false;
    continue;
  }
  if (/^ {2}aliases:\s*$/.test(line)) {
    inAliases = true;
    continue;
  }
  const alias = inAliases ? /^ {2}- (.+)$/.exec(line) : null;
  if (alias) {
    names.add(alias[1].replace(/^"|"$/g, ""));
  } else if (/^ {2}\S/.test(line)) {
    inAliases = false;
  }
}

const normalized = [
  ...new Set([...names].map((name) => name.toLowerCase().replace(/\s+/g, "-"))),
].sort();
const body = normalized.map((name) => `  ${JSON.stringify(name)},`).join("\n");
await writeFile(
  new URL("../extensions/librarian/github-languages.ts", import.meta.url),
  `// Generated by scripts/generate-github-languages.mjs from GitHub Linguist. Do not edit by hand.\nexport const GITHUB_LANGUAGES: ReadonlySet<string> = new Set([\n${body}\n]);\n`,
);
console.log(`${normalized.length} language names and aliases`);
